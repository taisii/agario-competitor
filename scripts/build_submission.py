from __future__ import annotations

import argparse
import ast
import hashlib
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "bots"))

from strategies.registry import (  # noqa: E402
    submission_strategy_names,
    submission_strategy_spec,
)


DEFAULT_OUTPUT = ROOT / "dist" / "my_bot.py"
DEFAULT_STRATEGY = "replay_dominance"
LOCAL_IMPORTS = {
    "simulation.rules",
    "strategies.base",
    "strategies.features",
    "strategies.greedy",
    "strategies.expected_final_mass",
    "strategies.local_tactical_search",
    "strategies.potential_field",
    "strategies.receding_horizon",
    "strategies.replay_imitation",
    "strategies.replay_profiles",
    "strategies.randomness",
    "strategies.world_transition",
}

HEADER = '''from __future__ import annotations

# Generated by scripts/build_submission.py. Edit the source strategy modules,
# then rebuild this file. The official portal accepts one Python file only.
'''

ENTRYPOINT_TEMPLATE = '''

def _read_framed_message(connection) -> str:
    """Read the starter-kit length-prefixed JSON without 1 KiB recopy loops."""

    prefix: list[str] = []
    for _ in range(8):  # Seven size digits plus the comma delimiter.
        character = connection._from_engine_pipe.read(1)
        if character == "":
            raise EOFError("Engine closed the pipe.")
        if character == ",":
            break
        if not character.isdecimal():
            raise RuntimeError("Invalid engine message size prefix.")
        prefix.append(character)
    else:
        raise RuntimeError("Invalid engine message size prefix.")

    if not prefix:
        raise RuntimeError("Invalid engine message size prefix.")
    size = int("".join(prefix))
    if size > 1_000_000:
        raise RuntimeError("Engine message exceeds the starter-kit limit.")

    chunks: list[str] = []
    remaining = size
    while remaining:
        chunk = connection._from_engine_pipe.read(remaining)
        if chunk == "":
            raise EOFError("Engine closed the pipe.")
        chunks.append(chunk)
        remaining -= len(chunk)
    return "".join(chunks)


def _install_fast_query_reader(game: Game) -> None:
    """Skip the one-member query union and decode its concrete model."""

    connection = game.connection

    def get_next_query() -> QueryMovePlayer:
        return QueryMovePlayer.model_validate_json(
            _read_framed_message(connection)
        )

    connection.get_next_query = get_next_query


def main() -> None:
    game = Game()
    _install_fast_query_reader(game)
    strategy = __STRATEGY_CLASS__()

    while True:
        try:
            query = game.get_next_query()
        except EOFError:
            break

        match query:
            case QueryMovePlayer():
                decision = strategy.choose(StrategyContext(game=game, query=query))
                game.send_move(decision.to_move(game.state.me.player_id))
            case _:
                raise RuntimeError(f"Unsupported query type: {type(query)}")


if __name__ == "__main__":
    main()
'''


def _without_local_imports(
    path: Path,
    local_only_classes: frozenset[str],
) -> str:
    source = path.read_text(encoding="utf-8")
    tree = ast.parse(source, filename=str(path))
    omitted_lines: set[int] = set()
    replacement_lines: dict[int, str] = {}

    # Local imports can appear inside a factory as well as at module scope.
    # Every bundled module shares one generated namespace, so remove all of
    # them while preserving explicit aliases used by the flattened source.
    for node in ast.walk(tree):
        if not (
            isinstance(node, ast.ImportFrom)
            and (node.module == "__future__" or node.module in LOCAL_IMPORTS)
        ):
            continue
        if node.module in LOCAL_IMPORTS:
            aliases = [
                f"{alias.asname} = {alias.name}\n"
                for alias in node.names
                if alias.asname is not None and alias.asname != alias.name
            ]
            if aliases:
                replacement_lines[node.lineno] = "".join(aliases)
        omitted_lines.update(range(node.lineno, (node.end_lineno or node.lineno) + 1))

    for node in tree.body:
        if not (isinstance(node, ast.ClassDef) and node.name in local_only_classes):
            continue
        omitted_lines.update(range(node.lineno, (node.end_lineno or node.lineno) + 1))

    return "".join(
        replacement_lines.get(line_number, "")
        + ("" if line_number in omitted_lines else line)
        for line_number, line in enumerate(source.splitlines(keepends=True), start=1)
    ).strip()


def _validate_submission(source: str, output: Path) -> None:
    tree = ast.parse(source, filename=str(output))
    forbidden: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            if node.module.split(".", 1)[0] in {
                "strategies",
                "telemetry",
            }:
                forbidden.append(node.module)
        elif isinstance(node, ast.Import):
            forbidden.extend(
                alias.name
                for alias in node.names
                if alias.name.split(".", 1)[0]
                in {"strategies", "telemetry"}
            )
    if forbidden:
        raise ValueError(f"Submission contains local imports: {sorted(set(forbidden))}")


def build_submission(
    output: Path = DEFAULT_OUTPUT,
    strategy_name: str = DEFAULT_STRATEGY,
) -> tuple[Path, str]:
    strategy_spec = submission_strategy_spec(strategy_name)
    bundle = strategy_spec.submission
    assert bundle is not None

    source_modules = tuple(ROOT / path for path in bundle.source_modules)
    local_only_classes = bundle.local_only_classes
    strategy_class = bundle.strategy_class

    source_fingerprint = hashlib.sha256()
    sections: list[str] = [HEADER.rstrip()]
    for path in source_modules:
        source_fingerprint.update(path.read_bytes())
        source_fingerprint.update(b"\0")
        sections.append(
            _without_local_imports(
                path,
                local_only_classes,
            )
        )

    fingerprint = source_fingerprint.hexdigest()
    sections.insert(1, f'# Source fingerprint: {fingerprint}')
    sections.append(
        ENTRYPOINT_TEMPLATE.replace("__STRATEGY_CLASS__", strategy_class).strip()
    )
    submission = "\n\n\n".join(sections) + "\n"
    _validate_submission(submission, output)

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(submission, encoding="utf-8")
    digest = hashlib.sha256(submission.encode("utf-8")).hexdigest()
    return output, digest


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the single-file Bot Battle submission")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--strategy",
        choices=submission_strategy_names(),
        default=DEFAULT_STRATEGY,
    )
    args = parser.parse_args()

    output, digest = build_submission(args.output.resolve(), args.strategy)
    print(f"Built {output} ({output.stat().st_size} bytes, sha256={digest})")


if __name__ == "__main__":
    main()
